// sidecar 打包：esbuild 把 runtime 门面 + 全部 workspace 依赖压成单文件 CJS
// （发行形态 = src-tauri bundle.resources 里的 sidecar/server.cjs，由宿主 node 拉起）。
// cli.cjs = 仓内开发控制面（同构建链第二入口，不进 bundle.resources、不随发行）。
import { build } from 'esbuild';

const common = {
  bundle: true,
  platform: 'node',
  format: 'cjs',
  // sidecar 只在 Tauri 线跑（Node 18+ 现代宿主）；Electron 22 兜底线不走本产物（那是同进程直连 runtime）。
  target: 'node18',
};

await build({
  entryPoints: ['src/server.ts'],
  outfile: 'dist/server.cjs',
  ...common,
  banner: { js: '// generated by scripts/bundle.mjs — attic sidecar RPC server' },
});
await build({
  entryPoints: ['src/cli.ts'],
  outfile: 'dist/cli.cjs',
  ...common,
  banner: { js: '// generated by scripts/bundle.mjs — attic dev CLI (not a product surface)' },
});
console.log('[sidecar] bundled -> dist/server.cjs + dist/cli.cjs');
